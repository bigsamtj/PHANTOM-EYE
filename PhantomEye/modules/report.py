"""Report Generation Module"""

from datetime import datetime
from utils.helpers import print_status

def generate_report(results: dict, output_file: str) -> str:
    lines = []
    lines.append("=" * 70)
    lines.append("          P H A N T O M   E Y E   R E P O R T")
    lines.append("          Offensive Security Automation Framework")
    lines.append("=" * 70)
    lines.append(f"Target      : {results.get('target', 'N/A')}")
    lines.append(f"Start Time  : {results.get('start_time', 'N/A')}")
    lines.append(f"End Time    : {results.get('end_time', 'N/A')}")
    lines.append(f"Generated   : {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append("=" * 70)

    recon = results.get("recon", {})
    lines.append("\n\n[1] RECONNAISSANCE")
    lines.append("-" * 50)
    lines.append(f"IP Address     : {recon.get('ip', 'N/A')}")
    lines.append(f"Open Ports     : {recon.get('ports', [])}")
    lines.append(f"Subdomains     : {len(recon.get('subdomains', []))} found")
    for sub in recon.get("subdomains", [])[:20]:
        lines.append(f"    • {sub}")
    if len(recon.get("subdomains", [])) > 20:
        lines.append(f"    ... and {len(recon.get('subdomains', []))-20} more")
    lines.append(f"\nTechnologies   : {recon.get('technologies', [])}")
    lines.append(f"\nDNS Records:")
    for rtype, records in recon.get("dns", {}).items():
        if records:
            lines.append(f"  {rtype}: {records}")

    vuln = results.get("vuln", {})
    lines.append("\n\n[2] VULNERABILITY ASSESSMENT")
    lines.append("-" * 50)
    lines.append(f"Sensitive Files Found : {len(vuln.get('sensitive_files', []))}")
    for item in vuln.get("sensitive_files", []):
        lines.append(f"  • {item.get('url')} [{item.get('status')}] (len={item.get('length')})")
    lines.append(f"\nMissing Security Headers: {vuln.get('missing_headers', [])}")
    lines.append(f"Interesting Findings  : {len(vuln.get('interesting_findings', []))}")
    for f in vuln.get("interesting_findings", [])[:10]:
        lines.append(f"  • {f}")

    owasp = results.get("owasp", {})
    lines.append("\n\n[3] OWASP TOP 10")
    lines.append("-" * 50)
    for key, data in owasp.items():
        if key == "tested_payloads":
            continue
        if isinstance(data, dict):
            findings = data.get("findings", [])
            lines.append(f"\n{key}:")
            lines.append(f"  Status   : {data.get('status', 'N/A')}")
            if findings:
                for f in findings:
                    lines.append(f"  - {f}")
            else:
                lines.append("  - No major findings in automated check")

    api = results.get("api", {})
    lines.append("\n\n[4] API SECURITY TOP 10")
    lines.append("-" * 50)
    lines.append(f"Discovered Endpoints: {len(api.get('discovered_endpoints', []))}")
    for ep in api.get("discovered_endpoints", []):
        lines.append(f"  • {ep.get('url')} [{ep.get('status')}] {ep.get('content_type', '')}")

    lines.append("\nAPI1 - BOLA/IDOR:")
    for f in api.get("api1_bola", {}).get("findings", []):
        lines.append(f"  - {f}")

    lines.append("\nAPI2 - Authentication:")
    for f in api.get("api2_auth", {}).get("findings", []):
        lines.append(f"  - {f}")

    lines.append("\nAPI5 - Function Level Authorization:")
    for f in api.get("api5_function_level", {}).get("findings", []):
        lines.append(f"  - {f}")

    payloads = results.get("payloads", {})
    lines.append("\n\n[5] PAYLOADS READY FOR TESTING")
    lines.append("-" * 50)
    for category, items in payloads.items():
        lines.append(f"\n[{category.upper()}] ({len(items)} payloads)")
        for p in items:
            lines.append(f"  {p}")

    lines.append("\n\n" + "=" * 70)
    lines.append("End of Report - Generated by PHANTOM EYE")
    lines.append("SYSTEM_OFFSEC")
    lines.append("=" * 70)

    content = "\n".join(lines)

    with open(output_file, "w", encoding="utf-8") as f:
        f.write(content)

    print_status(f"Report written to {output_file}", "success")
    return content
