def generate_text_report(target: Target, results: dict, findings: list) -> str:
    lines = []
    lines.append("=" * 70)
    lines.append("PHANTOM EYE — Security Assessment Report")
    lines.append(f"Version: {Config.VERSION}")
    lines.append("=" * 70)
    lines.append(f"Target        : {target.domain}")
    lines.append(f"IP Address    : {target.ip or 'N/A'}")
    lines.append(f"Started       : {results.get('started_at', 'N/A')}")
    lines.append(f"Finished      : {results.get('finished_at', 'N/A')}")
    lines.append(f"Duration      : {results.get('duration', 'N/A')} seconds")
    lines.append(f"Total Findings: {len(findings)}")
    lines.append("=" * 70)
    lines.append("")

    severity_order = ["critical", "high", "medium", "low", "info"]
    grouped = {s: [] for s in severity_order}

    for f in findings:
        sev = f.get("severity", "info").lower()
        if sev not in grouped:
            sev = "info"
        grouped[sev].append(f)

    for sev in severity_order:
        items = grouped[sev]
        if not items:
            continue

        lines.append(f"\n[{sev.upper()}] Findings ({len(items)})")
        lines.append("-" * 50)

        for i, item in enumerate(items, 1):
            lines.append(f"{i}. {item.get('title', 'Untitled')}")
            if item.get("url"):
                lines.append(f"   URL     : {item['url']}")
            if item.get("description"):
                lines.append(f"   Details : {item['description']}")
            lines.append(f"   Module  : {item.get('module', 'N/A')}")
            lines.append("")

    lines.append("=" * 70)
    lines.append("Report generated by PHANTOM EYE")
    lines.append(f"Author: {Config.AUTHOR}")
    lines.append("=" * 70)

    return "\n".join(lines)


